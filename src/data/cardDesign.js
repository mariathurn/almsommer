// Card number: hat 1, staff 2, grain 3, sheep 4, dogs 5-8, shepherds 9-12.
export function getCardNumber(card) {
    const base = { "9": 1, K: 2, "10": 3, A: 4 }[card.rank];
    if (base) return base;
    const suitIndex = suitOrder.indexOf(card.suit);
    return (card.rank === "U" ? 5 : 9) + suitIndex;
}

// Schafkopf points ("Augen") the card is worth, shown in the top-right circle.
export const cardPoints = { "9": 0, K: 4, "10": 10, A: 11, U: 2, O: 3 };

export function hasIllustratedDesign(card) {
    return Boolean(rankDesign[card.rank]?.art[card.suit]);
}
